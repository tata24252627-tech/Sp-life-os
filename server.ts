import express, { Request, Response } from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import 'dotenv/config';
import { GoogleGenAI } from '@google/genai';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const port = parseInt(process.env.PORT || '3000', 10);
const isProd = process.env.NODE_ENV === 'production';

app.use(express.json({ limit: '10mb' }));

// Shared Gemini AI instance
let aiClient: GoogleGenAI | null = null;
if (process.env.GEMINI_API_KEY) {
  aiClient = new GoogleGenAI({
    apiKey: process.env.GEMINI_API_KEY,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// AI Coprocessor Endpoint
app.post('/api/ai/chat', async (req: Request, res: Response) => {
  try {
    const { message, context } = req.body;

    if (!message || typeof message !== 'string') {
      res.status(400).json({ error: 'Message is required' });
      return;
    }

    if (!process.env.GEMINI_API_KEY || !aiClient) {
      // Re-check in case key was injected dynamically
      if (process.env.GEMINI_API_KEY) {
        aiClient = new GoogleGenAI({
          apiKey: process.env.GEMINI_API_KEY,
          httpOptions: { headers: { 'User-Agent': 'aistudio-build' } },
        });
      } else {
        res.json({
          role: 'assistant',
          content:
            'CONFIGURATION NOTICE: The external AI Provider API Key is not configured on this instance. Please set GEMINI_API_KEY in your deployment environment variables to activate live AI inference. (No simulated mock is returned in accordance with SP LIFE OS verification protocols).',
        });
        return;
      }
    }

    const systemInstruction = `You are SP LIFE OS Core Coprocessor, an advanced intelligence engine embedded inside SP LIFE OS – Ultimate Edition.
You assist the user with:
- Analyzing master data and spreadsheets
- Structuring daily tasks, deliverables, and prioritization
- Business operations, CRM pipeline, and inventory status
- Personal capital, bookkeeping, and budgeting in INR (₹)
- Designing schema architectures for dynamic modules
- General reasoning, automation scripts, and workflow optimization.

Keep answers concise, actionable, and formatted cleanly with markdown tables or bullet points where appropriate.
${context ? `Active context in user workspace: ${JSON.stringify(context)}` : ''}`;

    const response = await aiClient.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: message,
      config: {
        systemInstruction,
      },
    });

    const reply = response.text || 'No response generated by the coprocessor.';
    res.json({ role: 'assistant', content: reply });
  } catch (error: any) {
    console.error('Gemini API Error:', error);
    res.status(500).json({
      error: error?.message || 'Error occurred while contacting AI Coprocessor',
    });
  }
});

// System Health Check
app.get('/api/health', (_req, res) => {
  res.json({
    status: 'online',
    system: 'SP LIFE OS – Ultimate Edition',
    aiOnline: Boolean(process.env.GEMINI_API_KEY),
    timestamp: new Date().toISOString(),
  });
});

async function startServer() {
  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  }

  app.listen(port, '0.0.0.0', () => {
    console.log(`🚀 SP LIFE OS server active on http://0.0.0.0:${port}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
